"""Channel-family presets: the house style of a KIND of TV channel, year by year.

A channel is not a camera and not a tape. It is the whole delivery path a viewer
actually sat in front of: acquisition (film, a studio tube camera, an early CCD
head), the network master, the distribution hop that year (terrestrial RF, a cable
head end, a satellite transponder, an MPEG-2 multiplex) and finally the set in the
room, which is why every chain here ends in a picture tube or a panel and every
sound chain ends in that set's own speaker.

The variants follow the same logic: one is the studio-master line before
distribution, the other is the condition the signal arrived in (cable hop, off-air
tape, fringe reception, digital cliff).
"""

from ..engine.presets import ChainSpec, Preset, Variant, register_preset


def _crt_set(bloom: float, misconvergence: float = 0.0, *, combing: float = 0.5,
             twitter: float = 0.22, scan: float = 0.12, beam_bloom: float = 0.0,
             glass_glow: float = 0.0, curvature: float = 0.0, mask: str = "none",
             mask_strength: float = 0.14, mask_scale: float = 3.0,
             vignette_crt: float = 0.0) -> ChainSpec:
    """The viewer's picture tube: interlaced fields painted onto phosphor.

    Every channel preset that ends on a CRT ends on this pair, so a 1971 public
    station and a 1994 kids block differ by bloom, misconvergence and mask rather
    than by two people's private ideas of what a television is.
    """
    crt: dict = {"bloom": bloom, "scan_strength": scan, "misconvergence": misconvergence}
    if beam_bloom:
        crt["beam_bloom"] = beam_bloom
    if glass_glow:
        crt["glass_glow"] = glass_glow
    if curvature:
        crt["curvature"] = curvature
    if vignette_crt:
        crt["vignette_crt"] = vignette_crt
    if mask != "none":
        crt.update({"phosphor_mask": mask, "mask_strength": mask_strength,
                    "mask_scale": mask_scale})
    return [("interlace", {"field_order": "tff", "combing": combing, "twitter": twitter}),
            ("crt", crt)]


def _pal(strength: float, luma_bw: float = 3.8, chroma_bw: float = 0.9, *,
         dot_crawl: float = 0.14, rainbow: float = 0.07, comb: float = 0.35,
         fringing: float = 0.8) -> ChainSpec:
    """625-line PAL: phase alternation averages hue error away line by line.

    So no hue jitter and no differential-phase wander, which is exactly what makes
    a European studio read differently from an American one shot the same week:
    wider chroma bandwidth, stable faces, a little more cross-luma crawl.
    """
    return [("ntsc", {"system": "pal", "strength": strength, "luma_bw": luma_bw,
                      "chroma_bw": chroma_bw, "comb": comb, "rainbow": rainbow,
                      "dot_crawl": dot_crawl, "phase_noise": 0.0, "diff_phase": 0.0,
                      "fringing": fringing, "setup_level": 0.0})]


def _viewer_sound(device: str, strength: float = 0.45, *, buzz_db: float = -56.0,
                  hz: str = "60", comp: float = 0.4,
                  hum_db: float = -60.0) -> ChainSpec:
    """The last two links every channel shares: the sound carrier and the set.

    `a_tv_sound` is the intercarrier buzz of the transmission itself; `a_speaker`
    is the three-inch cone or the wooden console it finally left through.
    """
    return [("a_tv_sound", {"hz": hz, "buzz_db": buzz_db, "hum_db": hum_db, "comp": comp}),
            ("a_speaker", {"device": device, "strength": strength})]


def _broadcast_tape(luma_noise: float = 0.14, chroma_noise: float = 0.16, *,
                    luma_bw: float = 4.4, chroma_bw: float = 0.68,
                    head_switch: float = 0.06, dropouts: float = 0.2,
                    tbe: float = 0.1, sharpen: float = 0.3) -> ChainSpec:
    """The station's own VTR: two-inch quad, one-inch type C, Betacam SP.

    Broadcast machines are quiet, not silent, and a channel that carries no tape
    noise at all reads as somebody's clean modern footage with a filter on it.
    This is the floor: a little luma sand, a trace of head switching, composite
    chroma bandwidth. The off-air variants push the same effect to a home VCR.
    """
    return [("vhs", {"mode": "sp", "luma_bw": luma_bw, "chroma_bw": chroma_bw,
                     "chroma_delay": 0.8, "sharpen": sharpen, "luma_noise": luma_noise,
                     "chroma_noise": chroma_noise, "head_switch": head_switch,
                     "dropouts": dropouts, "dropout_burst": 0.2,
                     "time_base_error": tbe, "flagging": 0.04, "jitter_v": 0.05,
                     "generation": 1})]


def _home_vcr(mode: str = "sp", *, luma_noise: float = 0.3, chroma_noise: float = 0.3,
              generation: int = 1, dropouts: float = 1.2) -> dict:
    """What a domestic deck adds on top of the broadcast, as a variant override.

    Half the luma bandwidth, a quarter of the chroma, real head switching at the
    bottom of the frame and a time base that never quite settles.
    """
    return {"vhs.mode": mode, "vhs.luma_bw": 3.4, "vhs.chroma_bw": 0.42,
            "vhs.chroma_delay": 1.1, "vhs.sharpen": 0.5,
            "vhs.luma_noise": luma_noise, "vhs.chroma_noise": chroma_noise,
            "vhs.head_switch": 0.4, "vhs.dropouts": dropouts,
            "vhs.time_base_error": 0.28, "vhs.flagging": 0.12,
            "vhs.jitter_v": 0.14, "vhs.generation": generation}


def _off_air_tape_sound(fmt: str = "vhs_linear", *, noise_db: float = -50.0) -> ChainSpec:
    """The sound side of the same dormant VCR."""
    return [("a_video_tape_audio", {"enabled": False, "format": fmt, "tracking": 0.18,
                                    "dropout_rate": 2.0, "noise_db": noise_db,
                                    "head_switch_db": -62.0})]


def _film_insert(amount: float = 0.4, size: float = 1.8, chroma: float = 0.16, *,
                 layers: str = "color_neg", stock: str = "doc_16") -> ChainSpec:
    """A dormant 16 mm insert reel, sitting in the medium stage of a video chain.

    Studio channels everywhere cut to film for exteriors, wildlife, the crime
    series' location night: grain, an unsteady gate and a worn sprocket that the
    studio cameras never had. Off in the base chain; a variant turns the reel on.
    """
    return [("grain", {"enabled": False, "amount": amount, "size": size,
                       "chroma_grain": chroma, "stock": stock, "layers": layers,
                       "roughness": 0.55}),
            ("gate_weave", {"enabled": False, "amount": 1.1, "hz": 0.7,
                            "rotation": 0.05, "splice_bump": 0.8}),
            ("telecine_scan", {"enabled": False, "pin_stability": "sprocket_worn",
                               "hop_px": 0.7})]


